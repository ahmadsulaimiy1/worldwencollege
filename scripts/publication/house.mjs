/**
 * AIPC PRESS — THE HOUSE VISUAL IDENTITY.
 *
 * ────────────────────────────────────────────────────────────────────
 * WHAT A HOUSE IDENTITY IS FOR, AND WHY IT IS NOT THE SPECIFICATION
 * ────────────────────────────────────────────────────────────────────
 * The Production Specifications already describe one book exactly:
 * its trim, its stock, its ink limits, its finishing. That document is
 * measured, and everything in it is true of the flagship and of nothing
 * else. It cannot govern the second book, because it never anticipated
 * one.
 *
 * This file governs the second book. It answers the question a house
 * identity exists to answer: when a reader who owns one of our books
 * sees another on a shelf, what makes them recognise it as ours before
 * reading the title — and what makes them recognise it as a DIFFERENT
 * KIND of book without being told?
 *
 * Two systems answer that, and they must not be confused:
 *
 *   THE CONSTANTS never vary between publications. The crest, the two
 *   type families, the deep navy, the gold, the spine architecture,
 *   the folio position. These are the signature. A publication that
 *   departs from them is not a AIPC Press publication.
 *
 *   THE VARIABLES vary by publication family and only by family, along
 *   ONE axis each: format tells you the kind of book, the family colour
 *   tells you the shelf it belongs on, the cover field tells you whether
 *   it is for a learner, a teacher or an institution. One variable per
 *   distinction. Four variables carrying the same distinction is not
 *   a system, it is decoration agreeing with itself.
 *
 * ────────────────────────────────────────────────────────────────────
 * WHAT IS COMPUTED AND WHY THAT MATTERS
 * ────────────────────────────────────────────────────────────────────
 * A house identity written as prose drifts within two titles: the type
 * scale is restated slightly wrong, a colour is picked by eye from a
 * printed sample, a spine is estimated. So every number here that could
 * be derived IS derived — the trim and bleed from covers.mjs, the type
 * scale and the palettes from design.mjs, the spine from the same
 * caliper formula the flagship cover was produced with, and the family
 * colours are checked for contrast rather than asserted to be legible.
 *
 * The one thing not computed is the family assignment itself. Which hue
 * belongs to which family is a decision, and it is recorded as one.
 */
