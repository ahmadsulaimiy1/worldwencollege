// ─────────────────────────────────────────────────────────────────────
// 3 · THE MARGIN AND NAVIGATION SYSTEM
// ─────────────────────────────────────────────────────────────────────

/**
 * Margins as PROPORTIONS of the trim, not millimetres, so one rule
 * governs four formats. The ratios are the classical asymmetric set —
 * gutter smallest, foot largest — which puts the text block above
 * optical centre and leaves the thumb somewhere to rest.
 *
 * The gutter allowance is stated separately because it is not
 * aesthetic: it is the paper the binding eats, and it scales with
 * extent, not with trim.
 */
export const MARGINS = {
  ratios: { gutter: 0.090, head: 0.075, fore: 0.105, foot: 0.130 },
  note: 'Of trim width for gutter and fore-edge, of trim height for head and foot.',
  gutterAllowance: [
    ['Under 200 pages', 0, 'Perfect binding opens adequately; no extra allowance.'],
    ['200–400 pages', 3, 'Three millimetres added to the gutter on both sides.'],
    ['Over 400 pages', 5, 'Five millimetres, and no figure may cross the gutter at all.'],
  ],
};

/**
 * The measure ceiling exists because the margin ratios alone do not
 * produce a readable line at every format. Applied to the flagship trim
 * they yield a text block of about 89 characters — a third longer than
 * a reader can track a return sweep on — which is why the flagship
 * constrains its measure typographically, at the measure declared in
 * the type system, rather than relying on the margin. The ceiling makes that constraint part of the
 * system instead of a property of one book.
 */
MARGINS.maxMeasureChars = 75;

export function marginsFor(format, pages) {
  const f = formatFor(format);
  const extra = pages > 400 ? 5 : pages > 200 ? 3 : 0;
  const r = MARGINS.ratios;
  const gutter = round1(f.w * r.gutter + extra);
  let fore = round1(f.w * r.fore);
  const chars = (w) => Math.round(w / 1.9);
  const raw = chars(f.w - gutter - fore);
  // Widen the fore-edge until the measure is inside the ceiling. The
  // fore-edge rather than the gutter: the gutter is set by the binding.
  if (raw > MARGINS.maxMeasureChars) {
    fore = round1(f.w - gutter - MARGINS.maxMeasureChars * 1.9);
  }
  return {
    gutter,
    fore,
    head: round1(f.h * r.head),
    foot: round1(f.h * r.foot),
    measureChars: chars(f.w - gutter - fore),
    measureConstrained: raw > MARGINS.maxMeasureChars,
  };
}

const round1 = (n) => Math.round(n * 10) / 10;

