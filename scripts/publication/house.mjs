/**
 * The house identity's own audit: the assignments that could silently
 * go wrong, recomputed. Used by the Press volume and by the tests.
 */
export function houseEvidence() {
  const colours = familyColours();
  return {
    colours,
    typeOnly: colours.filter((c) => c.onNavy >= 4.5).map((c) => c.series),
    ruleOnly: colours.filter((c) => c.onNavy < 3 && c.onPaper < 3).map((c) => c.series),
    formats: FORMATS.map((f) => ({
      ...f, margins: marginsFor(f.key, 300),
    })),
    spines: [64, 160, 320, 441].map(spineFor),
    levelBars: LEVEL_PALETTES.length,
  };
}
