#!/usr/bin/env node
// Generates assets/art/guilloche.svg — the engraved rosette that sits
// behind the hero and the closing CTA band.
//
// WHY THIS IS GENERATED RATHER THAN DRAWN.
//
// Guilloché is the lathe-turned engraving used on banknotes, share
// certificates and watch dials. What makes it read as *engraved* rather
// than as decoration is that every curve is one continuous mathematical
// path — a hypotrochoid, the curve a point on a circle traces while
// that circle rolls inside a larger one — sampled at high resolution.
// Hand-drawing an approximation produces something that looks like a
// flower. Sampling the real curve produces something that looks like
// money, which is the entire point.
//
// Three rosettes are layered at different radii, phases and stroke
// weights so the interference between them creates the dense moiré that
// the real thing has.
//
//   node scripts/art/generate-guilloche.mjs
//
// Deterministic: same input constants in, byte-identical file out. Safe
// to re-run and diff.

import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, 'assets/art/guilloche.svg');

const SIZE = 620;
const CX = SIZE / 2;
const CY = SIZE / 2;

// A hypotrochoid: R = fixed circle, r = rolling circle, d = pen offset.
// The curve closes after r / gcd(R, r) revolutions, so the period is
// computed rather than guessed — an unclosed guilloché has a visible
// seam, and a seam is the one thing that gives away a fake engraving.
const gcd = (a, b) => (b ? gcd(b, a % b) : a);

function hypotrochoid({ R, r, d, scale, phase = 0, steps = 1100 }) {
  const turns = r / gcd(R, r);
  const period = 2 * Math.PI * turns;
  const pts = [];
  for (let i = 0; i <= steps; i++) {
    const t = phase + (i / steps) * period;
    const k = R - r;
    const x = k * Math.cos(t) + d * Math.cos((k / r) * t);
    const y = k * Math.sin(t) - d * Math.sin((k / r) * t);
    pts.push([CX + x * scale, CY + y * scale]);
  }
  // One decimal on a 620-unit viewBox is a tenth of a pixel at the size
  // this is ever rendered — invisible, and it takes the file from
  // 112 KB to roughly a quarter of that. A decorative background that
  // costs more than the stylesheet is a background that should not
  // ship, however good it looks.
  return 'M' + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L') + 'Z';
}

const ROSETTES = [
  { R: 240, r: 47,  d: 128, scale: 1.00, width: 0.55, opacity: 0.95 },
  { R: 210, r: 31,  d: 155, scale: 0.86, width: 0.45, opacity: 0.75, phase: 0.22 },
  { R: 260, r: 73,  d: 96,  scale: 0.66, width: 0.40, opacity: 0.6,  phase: 0.55 },
];

// Concentric hairlines, as on the border of an engraved certificate.
const RINGS = [
  { r: 296, width: 0.7, opacity: 0.55 },
  { r: 289, width: 0.35, opacity: 0.4 },
  { r: 152, width: 0.5, opacity: 0.45 },
];

const paths = ROSETTES.map(
  (o) =>
    `  <path d="${hypotrochoid(o)}" stroke-width="${o.width}" opacity="${o.opacity}"/>`
).join('\n');

const rings = RINGS.map(
  (o) =>
    `  <circle cx="${CX}" cy="${CY}" r="${o.r}" stroke-width="${o.width}" opacity="${o.opacity}"/>`
).join('\n');

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/art/generate-guilloche.mjs — do not hand-edit. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}" width="${SIZE}" height="${SIZE}">
  <g fill="none" stroke="#C7A24A" stroke-linejoin="round">
${rings}
${paths}
  </g>
</svg>
`;

mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, svg);
console.log(`Wrote ${path.relative(ROOT, OUT)} — ${(svg.length / 1024).toFixed(1)} KB`);
