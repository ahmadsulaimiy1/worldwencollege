/**
 * Self-hosts the three faces of the Register (`SEB §30.6`).
 *
 * No CDN dependency — a font that fails to load is a design failure, and
 * a third-party request on every page load is a dependency nobody
 * audited. Only the latin and latin-ext subsets are copied: the estate's
 * Arabic faces are governed separately (`SEB §7.6`) and are shipped with
 * the institution that needs them, not with the language.
 *
 * Deterministic: same input, same output, and the emitted CSS is diffable.
 */

import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src', 'fonts');
mkdirSync(out, { recursive: true });

/** family · fontsource package · variant · axes we actually use. */
const FACES = [
  {
    family: 'Fraunces Variable',
    pkg: '@fontsource-variable/fraunces',
    variant: 'full',
    // opsz 9–144, wght 100–900, SOFT 0–100, WONK 0–1
    weight: '100 900',
    stretch: null,
  },
  {
    family: 'Archivo Variable',
    pkg: '@fontsource-variable/archivo',
    variant: 'standard',
    weight: '100 900',
    stretch: '62% 125%',
  },
  {
    family: 'Cinzel Variable',
    pkg: '@fontsource-variable/cinzel',
    variant: 'wght',
    weight: '400 900',
    stretch: null,
  },
];

const SUBSETS = [
  {
    name: 'latin',
    range:
      'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
  },
  {
    name: 'latin-ext',
    range:
      'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF',
  },
];

const blocks = [
  '/* Generated by build/fonts.mjs — do not edit. Run `npm run fonts`. */',
  '/* Self-hosted, no CDN (SEB §30.6, §33.6). */',
  '',
];

let copied = 0;
for (const face of FACES) {
  const slug = face.pkg.split('/')[1];
  for (const subset of SUBSETS) {
    const file = `${slug}-${subset.name}-${face.variant}-normal.woff2`;
    const from = join(root, 'node_modules', face.pkg, 'files', file);
    try {
      copyFileSync(from, join(out, file));
      copied += 1;
    } catch {
      console.error(`  ! missing ${file} — the face will fall back. Check the package version.`);
      continue;
    }
    blocks.push(
      '@font-face {',
      `  font-family: '${face.family}';`,
      '  font-style: normal;',
      // `swap` and not `optional`: the Register carries the institution's
      // voice, and a fallback that never swaps is a different institution.
      '  font-display: swap;',
      `  font-weight: ${face.weight};`,
      ...(face.stretch ? [`  font-stretch: ${face.stretch};`] : []),
      `  src: url('./fonts/${file}') format('woff2-variations');`,
      `  unicode-range: ${subset.range};`,
      '}',
      '',
    );
  }
}

writeFileSync(join(root, 'src', 'fonts.css'), blocks.join('\n'));
console.log(`fonts: ${copied} file(s) self-hosted, src/fonts.css written`);
